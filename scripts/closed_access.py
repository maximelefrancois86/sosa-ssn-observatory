#!/usr/bin/env python3
"""The closed-access candidates of strata A and B without an S2ORC text, by platform.

    python3 -I scripts/closed_access.py

The works whose full text needs a subscription (or the authors): candidates of strata A and B
with a DOI, closed access in OpenAlex, and no S2ORC full text, the same population that
scripts/harvest_oa_fulltext.py leaves aside. The platform comes from the DOI prefix (OpenAlex
gives no publisher for a third of them); a prefix not in the table is shown as it is.
Writes results/closed-access.md and results/closed-access.csv (one line per work).
"""
import collections
import csv
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from strata import ROOT, load_corpus, load_seeds, stratum  # noqa: E402

PLATFORM = {
    "10.1007": "SpringerLink (Springer Nature)",
    "10.1109": "IEEE Xplore", "10.23919": "IEEE Xplore",  # 10.23919: IEEE co-sponsored conferences
    "10.1016": "ScienceDirect (Elsevier)",
    "10.1145": "ACM Digital Library",
    "10.4018": "IGI Global",
    "10.1002": "Wiley Online Library", "10.1111": "Wiley Online Library",
    "10.3233": "IOS Press", "10.1177": "SAGE (incl. IOS Press journals)",
    "10.1080": "Taylor & Francis", "10.1201": "Taylor & Francis",
    "10.70675": "theses.fr (ABES): French theses, no subscription",
    "10.1515": "De Gruyter",
    "10.1117": "SPIE Digital Library",
    "10.1108": "Emerald",
    "10.1142": "World Scientific",
    "10.1061": "ASCE Library",
    "10.2174": "Bentham Science",
    "10.1147": "IBM (IEEE Xplore)",
    "10.1017": "Cambridge University Press",
    "10.1504": "Inderscience",
    "10.1049": "IET (Wiley)",
    "10.2514": "AIAA",
    "10.3791": "JoVE",
    "10.2749": "IABSE",
    "10.1088": "IOP Publishing",
}


def main():
    role = {s["key"]: s["role"] for s in load_seeds()}
    items = [json.loads(l) for l in open(ROOT / "screening/items.jsonl", encoding="utf-8")]
    have = {it["doi"] for it in items if it["doi"] and it["item"].startswith("s2orc:")}
    pool = sorted((w for w in load_corpus() if stratum(w, role) in ("A", "B") and w["doi"]
                   and w["doi"].lower() not in have and w["oa_status"] in ("closed", "", None)),
                  key=lambda w: w["openalex"])
    by = collections.defaultdict(list)
    for w in pool:
        by[PLATFORM.get(w["doi"].split("/")[0], w["doi"].split("/")[0])].append(w)
    lines = ["# Closed-access candidates by platform", "",
             "Generated by `scripts/closed_access.py`. Candidates of strata A and B with a DOI, closed access",
             "in OpenAlex, and no S2ORC full text: their full text needs a subscription of the school, an",
             "inter-library loan, or the authors. The platform comes from the DOI prefix.", "",
             f"**{len(pool)} works**: {sum(stratum(w, role) == 'A' for w in pool)} in stratum A, "
             f"{sum(stratum(w, role) == 'B' for w in pool)} in B.", "",
             "| Platform | Works | A | B | Types | Main venues |", "|---|---:|---:|---:|---|---|"]
    for plat, ws in sorted(by.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        types = ", ".join(f"{t} {n}" for t, n in collections.Counter(w["type"] for w in ws).most_common(3))
        venues = "; ".join(f"{v or '?'} {n}" for v, n in collections.Counter(w["venue"] for w in ws).most_common(2))
        lines.append(f"| {plat} | {len(ws)} | {sum(stratum(w, role) == 'A' for w in ws)} | "
                     f"{sum(stratum(w, role) == 'B' for w in ws)} | {types} | {venues} |")
    (ROOT / "results/closed-access.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    with open(ROOT / "results/closed-access.csv", "w", newline="", encoding="utf-8") as f:
        out = csv.writer(f)
        out.writerow(["openalex", "doi", "stratum", "platform", "type", "year", "venue", "title"])
        for w in pool:
            out.writerow([w["openalex"], w["doi"], stratum(w, role), PLATFORM.get(w["doi"].split("/")[0],
                          w["doi"].split("/")[0]), w["type"], w["year"], w["venue"], w["title"]])
    print("\n".join(lines[8:]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
