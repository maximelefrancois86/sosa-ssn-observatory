#!/usr/bin/env python3
"""What the last retry of the open-access downloads gave, and what is left to fetch by hand.

    python3 -I scripts/oa_retry_report.py

Reads the last complete manifest of scripts/harvest_oa_retry.py (`pass`: `retry`). Writes
results/oa-retry.md (outcomes, sources, what blocks by host) and results/oa-unretrieved.csv:
the works still without a text, with their DOI and the URLs tried, for a download by hand in
a browser (a person passes the bot challenges that the scripts leave alone).
"""
import collections
import csv
import json
import pathlib
import sys
import urllib.parse

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from strata import ROOT  # noqa: E402


def site(url):
    host = urllib.parse.urlsplit(url).netloc.split(":")[0].lower()
    return host[4:] if host.startswith("www.") else host or "?"


def main():
    runs = [json.loads(m.read_text(encoding="utf-8")) for m in sorted(ROOT.glob("raw/*-oa-fulltext-manifest.json"))]
    man = [m for m in runs if m.get("complete") and m.get("pass") == "retry"][-1]
    left = [e for e in man["works"] if e["outcome"] != "text"]
    block = collections.defaultdict(collections.Counter)
    for e in left:
        for t in e["tried"]:
            why = t["outcome"] if t["outcome"] != "error" else t["error"].split("(")[0].replace("URLError", "network")
            block[site(t["url"])][why] += 1
    lines = ["# Retry of the failed open-access downloads", "",
             f"Generated by `scripts/oa_retry_report.py` from `raw/{man['stamp']}-oa-fulltext-manifest.json`",
             f"(`scripts/harvest_oa_retry.py`, after {', '.join(man['after'])}).", "",
             f"**{man['pool']} works** of strata A and B where a download had failed: "
             + ", ".join(f"{k} {v}" for k, v in sorted(man["outcomes"].items(), key=lambda kv: -kv[1])) + ".",
             "Texts by source: " + (", ".join(f"{k} {v}" for k, v in man["by_source"].items()) or "none") + ".",
             f"By stratum, still without a text: "
             + ", ".join(f"{s} {n}" for s, n in sorted(collections.Counter(e['stratum'] for e in left).items())) + ".",
             "", "A bot challenge (Anubis, reCAPTCHA, Cloudflare) is not solved by the scripts; the works",
             "are listed in `results/oa-unretrieved.csv` for a download by hand.", "",
             "| Site | Attempts | What answered |", "|---|---:|---|"]
    for s, c in sorted(block.items(), key=lambda kv: -sum(kv[1].values())):
        lines.append(f"| {s} | {sum(c.values())} | " + ", ".join(f"{k} {v}" for k, v in c.most_common()) + " |")
    (ROOT / "results/oa-retry.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    with open(ROOT / "results/oa-unretrieved.csv", "w", newline="", encoding="utf-8") as f:
        out = csv.writer(f)
        out.writerow(["openalex", "doi", "stratum", "outcome", "urls_tried"])
        for e in sorted(left, key=lambda e: (e["stratum"], e["openalex"])):
            out.writerow([e["openalex"], e["doi"], e["stratum"], e["outcome"],
                          " ".join(dict.fromkeys(t["url"] for t in e["tried"]))])
    print("\n".join(lines[5:8]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
